async page => {
  const base = 'http://127.0.0.1:47831/'
  const button = (name) => page.getByRole('button', {name,exact:true})
  const check = (ok,message) => {if(!ok)throw Error(message)}
  const outside = []
  await page.route('**/*',route=>{
    const url=route.request().url()
    if(url.startsWith(base)||!/^https?:/.test(url))return route.continue()
    outside.push(url)
    return route.abort()
  })
  await page.goto(base+'#practice/quiz')
  await button('Luyện câu').first().click()
  await page.getByRole('radio',{name:/Lập trình Hướng cấu trúc/}).click()
  await button('Nộp câu trả lời').click()
  await page.getByRole('heading',{name:'Lời giải tham khảo'}).waitFor()
  await page.getByText('✓ Đúng',{exact:true}).waitFor()
  await page.reload()
  await page.getByText('✓ Đúng',{exact:true}).waitFor()
  console.log('Trắc nghiệm đúng và còn kết quả sau reload.')

  await page.goto(base+'#practice/essay')
  await button('Luyện câu').first().click()
  const answer=page.getByRole('textbox',{name:'Bài làm tự luận'})
  await answer.fill('Bản nháp kiểm thử — lớp trừu tượng')
  await page.getByText('Đã lưu trên máy',{exact:true}).waitFor()
  await page.reload()
  await answer.waitFor()
  check((await answer.inputValue()).startsWith('Bản nháp'),'Lost essay draft')
  await button('Mở gợi ý 1').click()
  await button('Xem lời giải').click()
  await page.getByRole('heading',{name:'Lời giải tham khảo'}).waitFor()
  await page.getByRole('group',{name:/Tiêu chí tự chấm/}).getByRole('checkbox').first().click()
  console.log('Nháp, gợi ý và tiêu chí tự chấm hoạt động.')

  await page.goto(base+'#exam')
  await page.getByLabel('Số câu',{exact:true}).fill('2')
  await page.getByLabel('Phút tự đặt',{exact:true}).fill('1')
  await button('Bắt đầu thi thử').click()
  await page.getByRole('heading',{name:'Đề ghép luyện tập',exact:true}).waitFor()
  await button('Đánh dấu câu').click()
  await page.reload()
  await button('Đã đánh dấu').waitFor()
  check(await page.getByRole('heading',{name:'Lời giải tham khảo'}).count()===0,'Premature answer')
  await button('Kết thúc lượt').click()
  await button('Xác nhận nộp').click()
  await page.getByRole('heading',{name:'Kết quả lượt làm'}).waitFor()
  console.log('Thi thử lưu cờ qua reload, chỉ hiện kết quả sau nộp.')

  await page.goto(base+'#exam')
  await page.getByLabel('Cấu trúc đề').selectOption({label:'OOP - đề minh hoạ.pdf'})
  await page.getByLabel('Phút tự đặt',{exact:true}).fill('1')
  await button('Bắt đầu thi thử').click()
  await page.getByText('Câu 1 / 3',{exact:true}).waitFor()
  await page.clock.install()
  await page.clock.fastForward(61_000)
  await page.getByRole('heading',{name:'Kết quả lượt làm'}).waitFor()
  await page.reload()
  await page.getByRole('heading',{name:'Kết quả lượt làm'}).waitFor()
  await page.goto(base+'#edit/int1332-q001')
  await page.getByLabel('Nghi vấn, cách đọc, lời giải đề xuất và căn cứ').fill('Đối chiếu trong phiên kiểm thử riêng.')
  await button('Lưu hiệu đính cá nhân').click()
  await page.getByText('Đã lưu phiên bản hiệu đính cá nhân.',{exact:true}).waitFor()
  await page.reload()
  await page.getByText(/Kiểm tra thủ công của người dùng/).first().waitFor()
    await page.goto(base+'#backup')
  const downloading=page.waitForEvent('download')
  await button('Tải bản sao JSON').click()
  const download=await downloading
  await page.getByLabel('Chọn tệp JSON').setInputFiles(await download.path())
  await button('Xác nhận gộp').click()
  await page.getByText('Đã gộp bản sao.',{exact:true}).waitFor()
  console.log('Xuất/nhập JSON thành công.')

  await page.goto(base+'#library')
  await page.getByRole('searchbox').fill('Đề 6 14_01')
  await page.getByRole('link',{name:'Đề 6 14_01 kem dap an.pdf',exact:true}).click()
  const encoded=await page.getByTitle(/Đề 6.*trang 1/).getAttribute('src')
  const pdf=await page.request.get(new URL(encoded,base).href,{headers:{Range:'bytes=0-7'}})
  check(pdf.status()===206 && (await pdf.text()).startsWith('%PDF'),'Missing ranged Unicode PDF')
  check(outside.length===0,'External requests: '+outside.join(', '))
  await page.setViewportSize({width:390,height:844})
  await page.goto(base)
  await page.getByRole('heading',{name:'Bàn học OOP'}).waitFor()
  await button('Mục lục').click()
  await page.getByRole('link',{name:'Luyện tập',exact:true}).waitFor()
  await button('Đổi sang giao diện tối').click()
  check(await page.locator('html').getAttribute('data-theme')==='dark','Dark theme failed')
  await page.screenshot({path:'mobile-dark.png'})
  console.log('PDF Unicode đọc được, mọi yêu cầu mạng ở localhost, giao diện tối và menu mobile hoạt động.')
}
